#!/usr/bin/env node
// Copies the fixture responses the public-shell and Explore specimens draw into layouts/data.js, so
// every figure on those pages is what the mock API returns. Needs the mock server running:
//   node design-audit/mock/server.cjs --port 4399 --api-port 0
//   node design-audit/layouts/make-data.cjs [http://127.0.0.1:4399]
const fs = require('node:fs');
const path = require('node:path');

const base = process.argv[2] || 'http://127.0.0.1:4399';
const get = async (p, init) => {
  const res = await fetch(base + p, { headers: { Authorization: 'Bearer audit', 'Content-Type': 'application/json' }, ...init });
  return res.ok ? res.json() : null;
};

(async () => {
  await fetch(base + '/__mock/reset', { method: 'POST' });
  const search = await get('/api/properties/search?countyId=17&page=0&size=20');
  const parcels = await get('/api/parcels?bbox=-81,25,-80,26.5');
  const ids = search.content.map((r) => r.id);
  const predictions = (await get('/api/predictions/bulk', { method: 'POST', body: JSON.stringify({ propertyIds: ids }) })) || {};
  const id = 42;
  const property = await get(`/api/properties/id/${id}`);
  const valuation = await get(`/api/properties/id/${id}/valuation`);
  const history = await get(`/api/properties/id/${id}/valuations?page=0&size=10`);
  const out = {
    source: base + ' (design-audit/mock), ' + new Date().toISOString().slice(0, 10),
    search: { totalElements: search.totalElements, totalPages: search.totalPages, content: search.content },
    // Parcel centre per folio, from the parcel boundaries (one bounding-box call here; the app has
    // no batch lookup by folio, see DESIGN.md "Backend and store needs").
    centres: Object.fromEntries(parcels.map((p) => {
      const ring = p.geom.coordinates[0][0];
      const xs = ring.map((c) => c[0]), ys = ring.map((c) => c[1]);
      return [p.folio, [(Math.min(...ys) + Math.max(...ys)) / 2, (Math.min(...xs) + Math.max(...xs)) / 2]];
    })),
    predictions: Object.fromEntries(Object.entries(predictions).map(([k, p]) => [k, p])),
    property,
    valuation,
    history,
  };
  const file = path.join(__dirname, 'data.js');
  fs.writeFileSync(file, '// Generated by make-data.cjs from the mock fixtures. Do not edit by hand.\nwindow.FIX = ' + JSON.stringify(out, null, 1) + ';\n');
  console.log('wrote', path.relative(process.cwd(), file), (fs.statSync(file).size / 1024).toFixed(1) + ' kB');
  console.log('rows', out.search.content.length, 'centres', Object.keys(out.centres).length, 'predictions', Object.keys(out.predictions).length);
  console.log('prediction sample', JSON.stringify(Object.values(out.predictions)[0]).slice(0, 400));
  console.log('property keys', Object.keys(property).join(','));
  console.log('valuation keys', Object.keys(valuation).join(','), JSON.stringify(valuation.estimate), JSON.stringify(valuation.forecasts));
  console.log('history', JSON.stringify(history?.content?.slice(0, 3)));
})();
